export function getRandomCricketer(): Cricketer {
  const randomIndex = Math.floor(Math.random() * cricketers.length)
  return cricketers[randomIndex]
}

export function getDailyCricketer(): Cricketer {
  const today = new Date()
  const dateStr = `${today.getFullYear()}-${today.getMonth()}-${today.getDate()}`
  let hash = 0
  for (let i = 0; i < dateStr.length; i++) {
    const char = dateStr.charCodeAt(i)
    hash = ((hash << 5) - hash) + char
    hash = hash & hash
  }
  const index = Math.abs(hash) % cricketers.length
  return cricketers[index]
}

export function searchCricketers(query: string): Cricketer[] {
  const lowerQuery = query.toLowerCase()
  return cricketers.filter(c => 
    c.name.toLowerCase().includes(lowerQuery)
  )
}

export function getMatchesPlayedTogether(guessedId: string, targetId: string): number {
  const guessed = cricketers.find(c => c.id === guessedId)
  if (!guessed) return 0
  return guessed.teammates[targetId] || 0
}

export function getCommonTeams(guessedId: string, targetId: string): string[] {
  const guessed = cricketers.find(c => c.id === guessedId)
  const target = cricketers.find(c => c.id === targetId)
  if (!guessed || !target) return []
  
  const guessedTeams = new Set(guessed.playedWith)
  return target.playedWith.filter(team => guessedTeams.has(team))
}

export function getPlayerTeams(playerId: string, count: number = 2): string[] {
  const player = cricketers.find(c => c.id === playerId)
  if (!player) return []
  return player.playedWith.slice(0, count)
}
